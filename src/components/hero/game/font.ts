export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const GLYPH_GAP = 1;

export function textWidth(text: string) {
  return text.length ? text.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP : 0;
}

const cache = new Map<string, Sprite>();

/** The text as a sprite in one colour key (so it rasterises and caches like any other sprite). */
export function textSprite(text: string, key: string): Sprite {
  const id = `txt:${key}:${text}`;
  const hit = cache.get(id);
  if (hit) return hit;
  const rows = Array.from({ length: GLYPH_H }, (_, y) =>
    [...text]
      .map((ch) => (GLYPHS[ch] ?? GLYPHS[" "])[y].replace(/#/g, key))
      .join("."),
  );
  const s: Sprite = { id, w: textWidth(text), h: GLYPH_H, rows };
  cache.set(id, s);
  return s;
}
